/**
 * หาสถานที่ที่ถูกกล่าวถึงในข้อความ
 * - ถนน/จุดสังเกตมาก่อนเขต เพราะเฉพาะเจาะจงกว่า
 * - คำที่จับเป็นถนนแล้วจะถูกตัดออกก่อนค้นชื่อเขต (เช่น "ถนนลาดพร้าว" ไม่นับเป็นเขตลาดพร้าวซ้ำ)
 * @param {string} text
 * @returns {{name:string, lat:number, lon:number, kind:string, outside?:boolean}[]}
 */
export function findPlaces(text) {
  if (!text) return [];
  const found = [];
  let rest = text;
  for (const l of LANDMARKS) {
    const hits = l.match.filter((m) => rest.includes(m));
    if (hits.length === 0) continue;
    found.push(l);
    for (const m of hits) rest = rest.split(m).join(' ');
  }
  for (const d of BANGKOK_DISTRICTS) {
    if (rest.includes(d.name)) found.push(d);
  }
  return found;
}
